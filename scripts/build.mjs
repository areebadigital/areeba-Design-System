/**
 * Builds the areeba components from src/ (one folder per component) into:
 *   components/bundle.js   classic script for the artifact and Storybook: reads window.React, sets window.Areeba
 *   components/bundle.css  every component's CSS, in the order of src/css-order.json
 * Usage: node scripts/build.mjs           write the files
 *        node scripts/build.mjs --check   fail if the committed files are out of date or a source file is too long
 */
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const SRC = path.join(ROOT, 'src');
const check = process.argv.includes('--check');
const MAX_LINES = 1000, WARN_LINES = 300;

// React comes from the page (window.React) in the classic bundle.
const reactGlobal = {
  name: 'react-global',
  setup(b) {
    b.onResolve({ filter: /^react$/ }, () => ({ path: 'react', namespace: 'react-global' }));
    b.onLoad({ filter: /.*/, namespace: 'react-global' }, () => ({ contents: 'module.exports = window.React;', loader: 'js' }));
  },
};

const index = fs.readFileSync(path.join(SRC, 'index.js'), 'utf8');
const publicNames = [...index.matchAll(/export \{ ([^}]+) \}/g)].flatMap((m) => m[1].split(',').map((s) => s.trim()));
// Component cards the artifact lists: every public component with a README in components/<Name>/.
const cards = publicNames.filter((n) => /^[A-Z]/.test(n) && fs.existsSync(path.join(ROOT, 'components', n, 'README.md')));
const header = '/* @ds-bundle: ' + JSON.stringify({ format: 4, namespace: 'Areeba', components: cards.map((name) => ({ name })) }) + ' */\n'
  + '/* Generated by scripts/build.mjs from src/. Do not edit: change the modules in src/ and run `npm run build`. */\n';

const res = await build({
  stdin: { contents: "import * as A from './src/index.js';\nwindow.Areeba = Object.assign(window.Areeba || {}, A);\n", resolveDir: ROOT, sourcefile: 'areeba-global.js' },
  bundle: true, format: 'iife', target: 'es2017', charset: 'utf8', legalComments: 'inline', write: false, plugins: [reactGlobal], logLevel: 'error',
});
const js = header + res.outputFiles[0].text;

const order = JSON.parse(fs.readFileSync(path.join(SRC, 'css-order.json'), 'utf8'));
const onDisk = [];
(function walk(d) { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else onDisk.push(path.relative(SRC, p)); } })(SRC);
const strayCss = onDisk.filter((f) => f.endsWith('.css') && !order.includes(f));
const css = '/* Generated by scripts/build.mjs from src/ (order: src/css-order.json). Do not edit. */\n'
  + order.map((f) => fs.readFileSync(path.join(SRC, f), 'utf8').replace(/\n+$/, '')).join('\n\n') + '\n';

// Size budget: no source file over 1000 lines; flag files over 300.
const long = [], warn = [];
for (const f of onDisk.filter((f) => /\.(js|css)$/.test(f))) {
  const n = fs.readFileSync(path.join(SRC, f), 'utf8').split('\n').length;
  if (n > MAX_LINES) long.push(`${f} (${n} lines)`); else if (n > WARN_LINES) warn.push(`${f} (${n} lines)`);
}

// Motion comes only from tokens: no raw durations or curves in component CSS (styles/motion.css holds the shared keyframes).
const rawMotion = [];
for (const f of onDisk.filter((f) => f.endsWith('.css') && f !== 'styles/motion.css')) {
  fs.readFileSync(path.join(SRC, f), 'utf8').split('\n').forEach((l, i) => { if (/\b\d+m?s\b|cubic-bezier\(/.test(l)) rawMotion.push(`${f}:${i + 1}`); });
}

const problems = [];
if (rawMotion.length) problems.push('Raw motion values (use --duration-* and --ease-* tokens): ' + rawMotion.join(', '));
if (strayCss.length) problems.push('CSS files missing from src/css-order.json: ' + strayCss.join(', '));
if (long.length) problems.push(`Source files over ${MAX_LINES} lines (split them into smaller modules): ` + long.join(', '));
if (warn.length) console.warn(`Note: over ${WARN_LINES} lines, consider splitting: ` + warn.join(', '));

const targets = { 'components/bundle.js': js, 'components/bundle.css': css };
for (const [rel, text] of Object.entries(targets)) {
  const p = path.join(ROOT, rel);
  if (check) { if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== text) problems.push(`${rel} is out of date: run \`npm run build\` and commit it.`); }
  else fs.writeFileSync(p, text);
}
if (problems.length) { console.error(problems.map((p) => '✗ ' + p).join('\n')); process.exit(1); }
console.log(check ? '✓ components/bundle.* are up to date; every source file is under 1000 lines.' : `Built components/bundle.js (${cards.length} components, ${publicNames.length} exports) and components/bundle.css (${order.length} files).`);
